-- 辅助函数
function PosConfig:GetByIndex(index)
    for i, item in pairs(self.Coordinates) do
        if item.Index == index then
            return item
        end
    end
    return nil
end

function PosConfig:GetByPlanId(value)
    for i, item in pairs(self.Coordinates) do
        if item.PlanId == value then
            return item
        end
    end
    return nil
end

function PosConfig:GetAll()
